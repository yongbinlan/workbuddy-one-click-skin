param(
  [switch]$Check,
  [switch]$Remove,
  [string]$Node = "",
  [string]$Launcher = ""
)
$ErrorActionPreference = "Stop"
# NOTE: param() MUST be the first statement in this file -- see the long
# explanation at the top of _repoint-startup.ps1. Same reason here.
#
# NOTE: intentionally pure ASCII. PowerShell 5.1 parses a BOM-less .ps1 as
# ANSI/GBK on this machine, so non-ASCII literals (including a Chinese file
# name for the entry) would be mis-decoded and produce a garbled path.
#
# ===========================================================================
# WHY THIS FILE EXISTS  (2026-09-29, second real incident on the dev machine)
#
# The previous fix repointed WorkBuddy's OWN autostart entry
#     HKCU\Software\Microsoft\Windows\CurrentVersion\Run\WorkBuddy.WorkBuddy
# at our launcher vbs. That fix CANNOT HOLD, and here is the proof:
#
# WorkBuddy ships an auto-launch reconciler (src/main/features/desktop-host/
# auto-launch-controller.ts). On every startup it runs reconcileOnStartup()
# -> getEnabled(), which reads its own setting "autoLaunchDesired" and then:
#
#     if (desired === false) { setCurrentBundleAutoLaunch(false); return false; }
#     if (desired === true || settings.openAtLogin === true)
#         return enableCurrentBundleAutoLaunch(desired !== true);
#     ... default-on branch ...
#     return enableCurrentBundleAutoLaunch(true);
#
# and enableCurrentBundleAutoLaunch() unconditionally calls
#     app.setLoginItemSettings({ openAtLogin: true })
# which on Windows writes that Run value back to the app's OWN exe path.
#
# Every branch ends in that same write, so the value is rewritten on each
# app start. Observed on the dev machine:
#   * 09-24 11:27  we repointed the value at our vbs
#   * 09-27 08:02  the vbs ran (so the value was still ours at boot) and the
#                  app then started -- and rewrote the value in the same minute
#   * 09-28 10:29  app log: [AutoLaunch] read state {desired:true, openAtLogin:true}
#                  with no launcher log entry -> already back to the exe
#   * 09-29 09:24  same, and the user reported "the skin is gone again"
#
# The old design note claimed that keeping the value NAME untouched would make
# WorkBuddy read its switch as "still enabled" and leave us alone. That is
# exactly backwards: because getLoginItemSettings() finds the value present,
# openAtLogin reads as true, which guarantees the rewrite branch runs.
#
# So we stop fighting over that registry value and put our entry somewhere the
# app does not manage: the per-user Startup folder.
#
# ---------------------------------------------------------------------------
# WHY THE ENTRY DOES NOT JUST CALL workbuddy-skin-launcher.vbs
#
# That launcher STARTS WorkBuddy when it is not running. An entry that comes
# up at logon and does that would silently undo a user who deliberately turned
# WorkBuddy's autostart OFF -- we would be re-enabling it behind their back.
# Whether WorkBuddy starts at login is the user's decision, not ours.
#
# So the entry runs `launcher.mjs --no-launch`: wait for the debug port, then
# inject. If WorkBuddy never comes up it exits by itself after its bounded
# wait and logs that it found no port. Nothing is left running.
#
# Absolute paths ARE baked into the generated .vbs. That is deliberate and
# consistent with the shortcuts created by _make-shortcuts.ps1: this file is
# GENERATED on the target machine at install time, so the paths are correct
# for that machine. Re-run the initializer after moving the project folder.
# ===========================================================================

$root = Split-Path -Parent $PSScriptRoot
if (-not $Launcher) { $Launcher = Join-Path $root "tools\launcher.mjs" }
if (-not $Node) {
  # SKIN_NODE is probed once by the initializer and cached in launcher\env.cmd.
  $envCmd = Join-Path $root "launcher\env.cmd"
  if (Test-Path -LiteralPath $envCmd) {
    foreach ($line in (Get-Content -LiteralPath $envCmd)) {
      if ($line -match 'SKIN_NODE\s*=\s*"?([^"]+)"?') {
        $Node = $Matches[1].Trim().Trim('"')
        break
      }
    }
  }
}
if (-not $Node) { $Node = "node" }

$startup = [Environment]::GetFolderPath("Startup")
if (-not (Test-Path -LiteralPath $startup)) {
  Write-Output "NO-STARTUP-DIR (cannot locate the per-user Startup folder)"
  Write-Output "DONE"
  exit 1
}
$entry  = Join-Path $startup "WorkBuddySkinAutoInject.vbs"
$backup = Join-Path $root "backup"
if (-not (Test-Path -LiteralPath $backup)) { New-Item -ItemType Directory -Path $backup | Out-Null }

function Read-EntryText {
  if (-not (Test-Path -LiteralPath $entry)) { return "" }
  return (Get-Content -LiteralPath $entry -Raw)
}
function Test-IsOurs([string]$text) {
  return ($text -match "workbuddy-skin") -and ($text -match "Generated by tools")
}

# --------------------------------------------------------------------- check
Write-Output "--- startup folder: per-user logon entry ---"
Write-Output ("DIR " + $startup)
Write-Output ("ENTRY " + $entry)
$exists = Test-Path -LiteralPath $entry
Write-Output ("EXISTS " + $exists)
if ($exists) {
  $txt = Read-EntryText
  Write-Output ("OURS " + (Test-IsOurs $txt))
  Write-Output ("POINTS-AT-LAUNCHER " + ($txt -match [regex]::Escape($Launcher)))
}
Write-Output ("PLANNED-NODE " + $Node)
Write-Output ("PLANNED-LAUNCHER " + $Launcher)
if ($Check) { Write-Output "DONE"; exit 0 }

# -------------------------------------------------------------------- remove
if ($Remove) {
  if (-not $exists) { Write-Output "NOTHING-TO-REMOVE"; Write-Output "DONE"; exit 0 }
  if (-not (Test-IsOurs (Read-EntryText))) {
    # Not ours -> never delete it. Deleting another program's logon entry is
    # exactly the kind of overreach this project keeps refusing to do.
    Write-Output "NOT-OURS-LEAVE-ALONE"
    Write-Output "DONE"
    exit 0
  }
  Remove-Item -LiteralPath $entry -Force
  Write-Output ("REMOVED " + $entry)
  Write-Output ("GONE " + (-not (Test-Path -LiteralPath $entry)))
  Write-Output "DONE"
  exit 0
}

# ------------------------------------------------------------------- install
if ($exists -and -not (Test-IsOurs (Read-EntryText))) {
  # Never overwrite a foreign file. Move it aside first.
  $safe = [DateTime]::Now.ToString("yyyyMMdd-HHmmss")
  $bak  = Join-Path $backup ("startup-WorkBuddySkinAutoInject.vbs.foreign-" + $safe)
  Copy-Item -LiteralPath $entry -Destination $bak -Force
  Write-Output ("FOREIGN-BACKUP " + (Split-Path $bak -Leaf))
}

# Chr(34) is " -- using it avoids having to escape quotes inside the VBS
# string literal, which is where this kind of generated file usually breaks.
$tpl = @'
' Generated by tools\_install-startup-entry.ps1 -- do not edit by hand.
'
' PURPOSE
'   Make sure the CodeDrobe theme layer is present after logon.
'
' WHY THIS FILE EXISTS AT ALL
'   WorkBuddy rewrites its own HKCU Run autostart value on every start
'   (auto-launch-controller.ts -> reconcileOnStartup -> setLoginItemSettings),
'   so an entry placed there cannot survive. This one lives in the Startup
'   folder, which the app does not manage.
'
' WHY IT DOES NOT START WorkBuddy
'   Whether WorkBuddy starts at login is the user's decision. Starting it
'   here would silently undo anyone who turned that off. So this only injects,
'   and only once the app is actually up. It exits by itself when done.
'
'   Remove it by re-running the initializer with the remove flag, or just
'   delete this file.
Option Explicit
Dim sh, cmd
Set sh = CreateObject("WScript.Shell")
cmd = Chr(34) & "@NODE@" & Chr(34) & " " & Chr(34) & "@LAUNCHER@" & Chr(34) & " --no-launch"
' 0 = hidden window; False = do not wait (launcher.mjs exits on its own)
sh.Run cmd, 0, False
Set sh = Nothing
'@

$body = $tpl.Replace("@NODE@", $Node).Replace("@LAUNCHER@", $Launcher)

# -Encoding Default == the system ANSI code page (GBK here). That is what
# wscript.exe uses to parse a .vbs, so a project path containing non-ASCII
# characters survives. For an all-ASCII path the bytes are identical to ASCII.
Set-Content -LiteralPath $entry -Value $body -Encoding Default -NoNewline:$false

# Read back -- a write that is not read back is not a write. See the note in
# _repoint-startup.ps1 about a backup file that silently collapsed into one line.
$back = Read-EntryText
Write-Output ("WROTE " + $entry)
Write-Output ("READBACK " + ($back.Length -gt 0))
Write-Output ("VERIFY-OURS " + (Test-IsOurs $back))
Write-Output ("VERIFY-LAUNCHER " + ($back -match [regex]::Escape($Launcher)))
Write-Output ("VERIFY-NODE " + ($back -match [regex]::Escape($Node)))
Write-Output "DONE"
